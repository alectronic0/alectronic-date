"""js/labs-sync.js: per-source "last synced" date and live record count for the labs hub.

Derived from the published datasets themselves (scraped records carry lastSeen), so the
hub can never claim a sync that the data doesn't show.
"""

import io_content

SYNC_JS = io_content.REPO / "js" / "labs-sync.js"
CINEMA_PROVIDERS = {"taste-film": "fever", "adventure-cinema": "adventure-cinema"}
NERD_HOSTS = {"eventbrite": "eventbrite"}


def source_of(dataset, record):
    if dataset in ("activities", "workshops"):
        return (record.get("source") or "").lower()
    if dataset == "cinemaEvents":
        return CINEMA_PROVIDERS.get(record.get("provider"))
    if dataset == "nerdGatherings":
        return NERD_HOSTS.get(record.get("host"))
    return None


def scraped_records(labs):
    for name in ("activities", "workshops"):
        for record in io_content.load_geo(name):
            yield name, record
    for section in ("cinemaEvents", "nerdGatherings"):
        for record in labs.items(section):
            yield section, record


def summary(labs=None):
    labs = labs or io_content.LabsContent()
    sources = {}
    for dataset, record in scraped_records(labs):
        source = source_of(dataset, record)
        if not source or record.get("origin") != "auto" or not record.get("lastSeen"):
            continue
        entry = sources.setdefault(source, {"lastSynced": record["lastSeen"], "records": 0})
        entry["records"] += 1
        entry["lastSynced"] = max(entry["lastSynced"], record["lastSeen"])
    return dict(sorted(sources.items()))


def write(labs=None):
    body = io_content.dumps(summary(labs))
    SYNC_JS.write_text(f"// Generated by pipeline/sync.py - per-source last sync for labs/index.html\nwindow.LABS_SYNC = {body};\n", encoding="utf-8")
    return SYNC_JS
