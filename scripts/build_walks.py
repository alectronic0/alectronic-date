"""Build js/walks.js: a walking route from each Coffee & Bakeries spot to its nearest park.

    python3 scripts/build_walks.py

Routes come from the public OSM foot router (routing.openstreetmap.de), one request every
DELAY seconds, only for cafes with a park within MAX_KM. Re-run when cafes or parks change.
"""

import datetime
import json
import math
import sys
import time
import urllib.request
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "pipeline"))

from io_content import REPO, LabsContent  # noqa: E402

ROUTER = "https://routing.openstreetmap.de/routed-foot/route/v1/foot/{a};{b}?overview=full&geometries=geojson"
CAFE_CATEGORY = "Coffee & Bakeries"
PARK_CATEGORY = "Parks, Walks & Views"
NOT_PARKS = ("Sky Garden", "Horizon 22", "Rooftop Cinema")
MAX_KM = 1.25
MAX_MINUTES = 18
DELAY = 1.5
USER_AGENT = "date-alec-today-walk-builder"


def haversine_km(a, b):
    lat1, lng1, lat2, lng2 = map(math.radians, (a["lat"], a["lng"], b["lat"], b["lng"]))
    h = math.sin((lat2 - lat1) / 2) ** 2 + math.cos(lat1) * math.cos(lat2) * math.sin((lng2 - lng1) / 2) ** 2
    return 6371 * 2 * math.asin(math.sqrt(h))


def is_park(item):
    if item["category"] != PARK_CATEGORY:
        return False
    return not item["name"].startswith(NOT_PARKS)


def route(cafe, park):
    url = ROUTER.format(a=f"{cafe['lng']},{cafe['lat']}", b=f"{park['lng']},{park['lat']}")
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = json.load(response)
    if data.get("code") != "Ok":
        raise RuntimeError(f"router said {data.get('code')} for {cafe['name']}")
    best = data["routes"][0]
    coords = [[round(lat, 5), round(lng, 5)] for lng, lat in best["geometry"]["coordinates"]]
    return {
        "cafe": cafe["name"],
        "park": park["name"],
        "minutes": round(best["duration"] / 60),
        "km": round(best["distance"] / 1000, 1),
        "coords": coords,
    }


def main():
    items = LabsContent().items("dateIdeas")
    parks = [i for i in items if is_park(i)]
    cafes = [i for i in items if i["category"] == CAFE_CATEGORY]
    walks = []
    for cafe in cafes:
        park = min(parks, key=lambda p: haversine_km(cafe, p))
        if haversine_km(cafe, park) > MAX_KM:
            print(f"skip {cafe['name']}: nearest park {park['name']} too far")
            continue
        walk = route(cafe, park)
        time.sleep(DELAY)
        if walk["minutes"] > MAX_MINUTES:
            print(f"skip {cafe['name']}: {walk['minutes']} min to {park['name']}")
            continue
        print(f"{cafe['name']} -> {park['name']}: {walk['minutes']} min, {walk['km']} km")
        walks.append(walk)
    header = f"// Generated by scripts/build_walks.py on {datetime.date.today().isoformat()}. Routes (c) OpenStreetMap contributors.\n"
    (REPO / "js" / "walks.js").write_text(header + "window.WALKS = " + json.dumps(walks, ensure_ascii=False) + ";\n")
    print(f"{len(walks)} walks written")


if __name__ == "__main__":
    main()
